import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

// Run without a separate test framework or any network service.
const urls = new Map()
function moduleUrl(relative) {
  const file = path.resolve(relative)
  if (urls.has(file)) return urls.get(file)
  let source = ts.transpileModule(fs.readFileSync(file, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext },
  }).outputText
  source = source.replace(/from ['"](\.\/[^'"]+)['"]/g, (_match, dependency) =>
    `from ${JSON.stringify(moduleUrl(path.resolve(path.dirname(file), `${dependency}.ts`)))}`)
  const url = `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
  urls.set(file, url)
  return url
}
const load = relative => import(moduleUrl(relative))
